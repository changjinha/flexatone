// --------------------------------------------------------------------------
// Language state (module-local; state.js keeps appState.lang in sync via setLang)
// 언어 상태 (모듈 내부; state.js가 setLang으로 appState.lang과 동기화)
// --------------------------------------------------------------------------
let currentLang = DEFAULT_LANG;

export function isSupportedLang(lang) {
  return Object.prototype.hasOwnProperty.call(LANGUAGES, lang);
}

/** @returns {'en'|'ko'} */
export function getLang() {
  return currentLang;
}

/** Set current language; unknown codes fall back to DEFAULT_LANG. Returns the applied code. */
export function setLang(lang) {
  currentLang = isSupportedLang(lang) ? lang : DEFAULT_LANG;
  return currentLang;
}

/** Next language in the EN ⇄ KO toggle cycle. / 토글 순환상 다음 언어 */
export function nextLang(lang = currentLang) {
  return (LANGUAGES[lang] || LANGUAGES[DEFAULT_LANG]).next;
}

function formatTemplate(str, args) {
  if (!args.length) return str;
  return str.replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? String(args[i]) : m));
}

/**
 * Translate a key in the current language.
 * Fallback order: current lang → English → the key itself.
 * 현재 언어 → 영어 → 키 자체 순으로 대체.
 * @param {string} key
 * @param {...any} args  passed to function values or `{n}` placeholders
 * @returns {string}
 */
export function t(key, ...args) {
  const val = I18N[currentLang]?.[key] ?? I18N[DEFAULT_LANG]?.[key];
  if (val === undefined) return key;
  if (typeof val === 'function') return String(val(...args));
  return formatTemplate(String(val), args);
}

/** Pick from a bilingual object like `{ en: 'Risset Tone', ko: '리세 톤' }` (plugin names). */
export function pickLocalized(obj, lang = currentLang) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] ?? obj[DEFAULT_LANG] ?? Object.values(obj)[0] ?? '';
}

/** Keys missing in either language (used by runSelfCheck). / en·ko 누락 키 목록 */
export function findMissingI18nKeys() {
  const en = Object.keys(I18N.en);
  const ko = Object.keys(I18N.ko);
  const koSet = new Set(ko);
  const enSet = new Set(en);
  return {
    missingInKo: en.filter((k) => !koSet.has(k)),
    missingInEn: ko.filter((k) => !enSet.has(k)),
  };
}
